"""
Regenerate the results sections of README.md from the store.

    python scripts/update_readme.py           # rewrite the generated blocks
    python scripts/update_readme.py --check   # exit 1 if README is out of date

Only text between markers like

    <!-- generated:results -->
    ...
    <!-- /generated:results -->

is replaced. Every number AND every sentence that depends on a result (who
beat whom, whether anything is significant, which assets lack a regime) is
computed here from data/regime_store.db and data/variants.json.

Why: AGENTS.md rule 5 says no number goes into the docs unless code produced
it. Hand-copying tables after each run is exactly how stale or wrong claims
crept into earlier versions of this README.
"""
import argparse
import json
import os
import re
import sys

import numpy as np

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from src.analysis.forward import FORWARD_CYCLE, freeze_status, load_freeze  # noqa: E402
from src.dashboard import data  # noqa: E402  (read-only store queries)
from src.dashboard.theme import ASSET_NAMES, REGIME_LABELS, STRATEGY_NAMES  # noqa: E402

README = "README.md"
DB = "data/regime_store.db"
VARIANTS = "data/variants.json"
ALPHA = 0.05
# Order in tables: baselines first, the HMM last (and bold).
TABLE_ORDER = ["buy_hold", "dma200", "vol_target", "hmm"]
SHORT = {"buy_hold": "Buy & Hold", "dma200": "200-day MA", "vol_target": "Vol. target", "hmm": "HMM"}


def pct(x, digits=1, sign=False):
    return "–" if x is None or np.isnan(x) else f"{x:{'+' if sign else ''}.{digits}%}"


def num(x, digits=2, sign=False):
    return "–" if x is None or np.isnan(x) else f"{x:{'+' if sign else ''}.{digits}f}"


def names(ids):
    return ", ".join(ASSET_NAMES[a] for a in ids) if ids else "none"


class Store:
    """Everything the README needs, loaded once."""

    def __init__(self, db=DB, variants=VARIANTS, freeze_path="config/freeze.json"):
        self.db, self.variants, self.freeze_path = db, variants, freeze_path
        data.check_store(db)
        self.run = data.load_run(db)
        self.run_id = self.run["run_id"]
        self.cfg = json.loads(self.run["config_json"])
        self.windows = data.load_windows(db, self.run_id)
        self.assets = [a for a in self.cfg["backtest"]["assets"] if a in self.windows.index]
        self.m = data.load_metrics(db, self.run_id)
        self.sig = data.load_significance(db, self.run_id)
        self.strategies = [s for s in TABLE_ORDER if s in self.m.index.get_level_values(1)]
        self.baselines = [s for s in self.strategies if s != "hmm"]

    def metric(self, asset, strategy, name):
        return float(self.m.loc[(asset, strategy), name])


