def block_status(st):
    freeze = load_freeze(st.freeze_path)
    cash = st.cfg["backtest"].get("cash_ticker")
    instruments = st.cfg["backtest"].get("instruments") or {}
    traded = ", ".join(f"{ASSET_NAMES[a]} → {instruments.get(a, st.cfg['tickers'][a])}" for a in st.assets)
    lines = [
        "> **Status:** all 9 steps of the improvement roadmap are complete"
        + (f"; the design is frozen as {freeze['version']}" if freeze else "")
        + " (see [Roadmap](#9-roadmap) and the forward test below). "
        f"Every number in Section 1 is generated by `scripts/update_readme.py` from `data/regime_store.db`, "
        f"built by `scripts/run_pipeline.py` on data up to **{st.run['data_end']}**.",
        ">",
        f"> Traded instruments: {traded}. Uninvested cash earns "
        + (f"the 3-month T-bill yield ({cash})." if cash else "0%."),
    ]
    rerun = _variants_reproduce(st)
    if rerun is not None:
        lines.append(">")
        lines.append(f"> Reproducibility: a separate from-scratch run (`scripts/compare_variants.py`) "
                     f"matches every headline metric in this store to within {rerun:.0e}.")
    return "\n".join(lines)


def _variants_reproduce(st):
    """Largest difference between the 'current' variant and the store, or None."""
    if not os.path.exists(st.variants):
        return None
    current = next((v for v in json.load(open(st.variants))["variants"] if v["key"] == "current"), None)
    if current is None or current.get("source") == "store":  # a copy of the store proves nothing
        return None
    diffs = [abs(vals[k] - st.metric(a, s, k))
             for a, by in current["assets"].items() if a in st.assets
             for s, vals in by.items() if s in st.strategies
             for k in vals]
    worst = max(diffs) if diffs else None
    return max(worst, 1e-12) if worst is not None and worst < 1e-6 else None


def block_headline(st):
    def wins(metric, baseline, higher=True):
        return [a for a in st.assets
                if (st.metric(a, "hmm", metric) > st.metric(a, baseline, metric)) == higher
                and st.metric(a, "hmm", metric) != st.metric(a, baseline, metric)]

    n = len(st.assets)
    sig = st.sig[st.sig["p_value_holm"] < ALPHA]
    sharpe_bh = wins("Sharpe", "buy_hold")
    sharpe_all = [a for a in st.assets if all(st.metric(a, "hmm", "Sharpe") > st.metric(a, b, "Sharpe")
                                              for b in st.baselines)]
    dd_bh = wins("Max DD", "buy_hold")  # Max DD is negative: higher = smaller loss
    vol_bh = wins("Ann. Vol", "buy_hold", higher=False)

    if sig.empty:
        answer = "**Answer: not proven.**"
        sig_text = (f"**None of the {len(st.sig)} Sharpe-ratio differences is statistically significant** after "
                    f"correcting for multiple tests (smallest adjusted p = {st.sig['p_value_holm'].min():.2f}), "
                    "so the data cannot tell the HMM apart from its baselines.")
    else:
        # A significant difference can go either way: say which.
        better, worse = sig[sig["sharpe_diff"] > 0], sig[sig["sharpe_diff"] < 0]

        def pairs(df):
            return ", ".join(f"{ASSET_NAMES[r.asset_id]} vs {SHORT[r.baseline]} (adjusted p = {r.p_value_holm:.3f})"
                             for r in df.itertuples())

        answer = "**Answer: partly.**" if not better.empty else "**Answer: no edge shown.**"
        sig_text = ""
        if not better.empty:
            sig_text += f"The HMM's Sharpe is significantly **higher** for {pairs(better)}. "
        else:
            sig_text += "**No difference in the HMM's favour is statistically significant.** "
        if not worse.empty:
            sig_text += (f"It is significantly **lower** than the baseline for {pairs(worse)}, after correcting "
                         f"for all {len(st.sig)} tests.")

    return "\n".join([
        "**Question:** Can an unsupervised HMM detect market regimes early enough to improve a portfolio, "
        "and does any edge survive trading costs?",
        "",
        f"{answer} Out-of-sample and after costs, the HMM strategy had lower volatility than buy-and-hold on "
        f"{len(vol_bh)} of {n} assets and a smaller maximum drawdown on {len(dd_bh)} of {n}. Its Sharpe ratio "
        f"(above cash) beat buy-and-hold on {len(sharpe_bh)} of {n} ({names(sharpe_bh)}) and beat every "
        f"baseline, including simple volatility targeting, on {len(sharpe_all)} of {n} ({names(sharpe_all)}). "
        + sig_text,
    ])


def block_results(st):
    rows = ["| Asset (traded, window) | Strategy | CAGR | Ann. Vol | Sharpe | Max DD | Avg. Exposure "
            "| 95% VaR (1d) | 99% CVaR (1d) |",
            "|---|---|---|---|---|---|---|---|---|"]
    instruments = st.cfg["backtest"].get("instruments") or {}
    for a in st.assets:
        w = st.windows.loc[a]
        label = (f"**{ASSET_NAMES[a]}** ({instruments.get(a, st.cfg['tickers'][a])}, "
                 f"{w['oos_start']:%Y-%m} to {w['oos_end']:%Y-%m})")
        for i, s in enumerate(st.strategies):
            name = f"**{STRATEGY_NAMES[s]}**" if s == "hmm" else STRATEGY_NAMES[s]
            g = lambda k: st.metric(a, s, k)  # noqa: E731
            rows.append(f"| {label if i == 0 else ''} | {name} | {pct(g('CAGR'), 2)} | {pct(g('Ann. Vol'), 2)} "
                        f"| {num(g('Sharpe'))} | {pct(g('Max DD'), 2)} | {pct(g('Avg. Exposure'), 0)} "
                        f"| {pct(g('VaR 95% (Hist)'), 2)} | {pct(g('CVaR 99% (Hist)'), 2)} |")
    btc_years = st.metric("bitcoin", "hmm", "Years") if "bitcoin" in st.assets else None
    note = ("*Returns are the traded instrument's total returns (adjusted prices, so dividends and fund fees are "
            "included); uninvested cash earns the 3-month T-bill rate. Sharpe = mean / std of daily returns "
            "**above cash** × √(rows per year): 252 for equities and gold, 365 for Bitcoin. VaR and CVaR are "
            "historical, 1-day, shown as positive losses.")
    if btc_years:
        note += f" Bitcoin's window is only {btc_years:.1f} years, so its numbers are the least reliable."
    return "\n".join(rows) + "\n\n" + note + "*"


def block_significance(st):
    order = {a: i for i, a in enumerate(st.assets)}
    sig = st.sig.assign(o=st.sig["asset_id"].map(order),
                        b=st.sig["baseline"].map({b: i for i, b in enumerate(st.baselines)})).sort_values(["o", "b"])
    rows = ["| Asset | HMM vs | Sharpe diff | 95% CI | p (bootstrap) | p (HAC) | p (Holm-adjusted) |",
            "|---|---|---|---|---|---|---|"]
    for r in sig.itertuples():
        rows.append(f"| {ASSET_NAMES[r.asset_id]} | {SHORT[r.baseline]} | {num(r.sharpe_diff, sign=True)} "
                    f"| [{num(r.ci_lower, sign=True)}, {num(r.ci_upper, sign=True)}] | {r.p_value:.3f} "
                    f"| {r.p_value_hac:.3f} | {r.p_value_holm:.3f} |")
    contains_zero = int(((sig["ci_lower"] <= 0) & (sig["ci_upper"] >= 0)).sum())
    agree = np.corrcoef(sig["p_value"], sig["p_value_hac"])[0, 1] if len(sig) > 2 else np.nan
    text = (f"**Reading this:** {contains_zero} of {len(sig)} 95% intervals contain zero, and the lowest raw "
            f"p-value is {sig['p_value'].min():.3f}. The bootstrap and HAC p-values have a correlation of "
            f"{agree:.2f} across the tests, a check that the two methods agree.")
    return "\n".join(rows) + "\n\n" + text


def block_variants(st):
    if not os.path.exists(st.variants):
        return "*Run `python scripts/compare_variants.py` to generate this comparison.*"
    v = json.load(open(st.variants))
    rows = ["| Asset | Setup | HMM Sharpe | Buy & Hold Sharpe | HMM CAGR | HMM Max DD | Transition days |",
            "|---|---|---|---|---|---|---|"]
    labels = {"step5": "Step 5", "labeling": "+ relative labels", "anchors": "+ Sharpe anchors",
              "funds": "+ funds & cash", "current": "+ regime sizing (now)", "volscale": "+ vol scaling (option)",
              "btc6": "now, Bitcoin 6 states (option)"}
    for a in st.assets:
        for i, var in enumerate(v["variants"]):
            res = var["assets"].get(a, {})
            h, b = res.get("hmm", {}), res.get("buy_hold", {})
            share = res.get("regime_share", {}).get("Transition", 0.0)
            rows.append(f"| {ASSET_NAMES[a] if i == 0 else ''} | {labels.get(var['key'], var['key'])} "
                        f"| {num(h.get('Sharpe'))} | {num(b.get('Sharpe'))} | {pct(h.get('CAGR'), 2)} "
                        f"| {pct(h.get('Max DD'), 1)} | {pct(share, 0)} |")
    no_trans = {var["key"]: [a for a in st.assets if var["assets"].get(a, {}).get("regime_share", {})
                             .get("Transition", 0) == 0] for var in v["variants"]}
    from_store = [labels.get(var["key"], var["key"]) for var in v["variants"] if var.get("source") == "store"]
    text = (f"Each row re-runs the whole pipeline with one more change (`scripts/compare_variants.py`, data to "
            f"{v.get('data_end')})")
    text += (f", except {', '.join(from_store)}, which is read from the main store." if from_store else ".")
    text += (f" Assets with no Transition days: {names(no_trans.get('step5', []))} under the Step 5 rule, "
             f"{names(no_trans.get('current', []))} now. Rows before \"+ funds & cash\" measure Sharpe on raw "
             "returns (cash at 0%); from that row on, Sharpe is measured above the T-bill rate, so part of that "
             "change is a change of yardstick, applied equally to every strategy.")
    options = {"volscale": "regime-aware volatility scaling", "btc6": "a 6-state Bitcoin model"}
    measured = [options[k] for k in options if k in no_trans]
    pending = [options[k] for k in v.get("not_measured", []) if k in options]
    if measured:
        text += f" Rows marked \"option\" ({', '.join(measured)}) are not used by default."
    if pending:
        text += (f" Not yet measured: {' and '.join(pending)} (options, off by default); "
                 "`python scripts/compare_variants.py` adds them (about 25 minutes).")
    text += (" Several setups have now been run on the same out-of-sample years, so read differences between "
             "rows as exploratory.")
    return "\n".join(rows) + "\n\n" + text


def block_episodes(st):
    spx = "spx"
    pm = data.load_period_metrics(st.db, st.run_id, spx)
    eps = pm[pm["kind"] == "episode"]
    episodes = st.cfg.get("evaluation", {}).get("stress_episodes", {})
    order = sorted((e for e in episodes if e in set(eps["period"])), key=lambda e: episodes[e][0])
    header = ("| Episode (S&P 500 peak → trough) | " + " | ".join(SHORT[s] for s in st.strategies)
              + " | HMM avg. exposure |")
    rows = [header, "|" + "---|" * (len(st.strategies) + 2)]
    beat = {b: 0 for b in st.baselines}
    for e in order:
        sub = eps[eps["period"] == e].set_index("strategy")
        tr = {s: sub.loc[s, "Total Return"] for s in st.strategies}
        for b in st.baselines:
            beat[b] += tr["hmm"] > tr[b]
        rows.append(f"| {e.replace('_', ' ').capitalize()} ({episodes[e][0]} → {episodes[e][1]}) | "
                    + " | ".join(pct(tr[s], sign=True) for s in st.strategies)
                    + f" | {pct(sub.loc['hmm', 'Avg. Exposure'], 0)} |")
    text = ("The HMM lost less than " + ", ".join(f"{SHORT[b]} in {beat[b]} of {len(order)}" for b in st.baselines)
            + " episodes.")
    return "\n".join(rows) + "\n\n" + text


def block_profile(st):
    prof = data.load_profiles(st.db, st.run_id, "spx")
    rows = ["| S&P 500 regime | Share of days | Avg. spell (days) | Ann. return | Ann. vol |", "|---|---|---|---|---|"]
    for lab, r in prof.iterrows():
        rows.append(f"| {lab} | {pct(r['share'], 0)} | {r['avg_spell_days']:.0f} | {pct(r['ann_return'], 1, True)} "
                    f"| {pct(r['ann_vol'], 1)} |")
    best = prof["ann_return"].idxmax()
    calmest = prof["ann_vol"].idxmin()
    if best == calmest:
        text = (f"The calmest regime ({best}) also had the best returns, so stepping aside in the other regimes "
                "gave up relatively little.")
    else:
        text = (f"The calmest regime is {calmest}, but the best average returns came on **{best}** days. Big "
                "rebounds cluster with big sell-offs, so a strategy that steps aside when volatility rises avoids "
                "some crashes and also misses the rebounds that follow.")
    return "\n".join(rows) + "\n\n" + text


def block_caveats(st):
    exp = [st.metric(a, "hmm", "Avg. Exposure") for a in st.assets]
    no_trans = []
    for a in st.assets:
        prof = data.load_profiles(st.db, st.run_id, a)
        if "Transition" not in prof.index:
            no_trans.append(a)
    lines = [f"- **Lower exposure explains part of the risk reduction.** The HMM is {min(exp):.0%}–{max(exp):.0%} "
             "invested on average, so some of its lower volatility and drawdown simply comes from holding less. "
             "The volatility-target baseline is there to separate that effect from regime detection."]
    if no_trans:
        lines.append(f"- **No Transition regime for {names(no_trans)}** out-of-sample: the model's states "
                     "for it are all rallies or sell-offs (see [Section 2C](#c-state-labeling-per-fold)).")
    else:
        lines.append(f"- **Every asset now has all three regimes** ({', '.join(REGIME_LABELS)}) out-of-sample.")
    return "\n".join(lines)


def block_forward(st):
    freeze = load_freeze(st.freeze_path)
    status, message = freeze_status(freeze, st.run["config_hash"])
    if status == "none":
        return "*The design has not been frozen yet.*"
    if status == "invalid":
        return f"> **Forward test invalid.** {message}"
    lines = [f"**{freeze['version']}** was frozen on **{freeze['frozen_on']}** (git tag `{freeze['version']}`). "
             f"Everything above was used while designing it. Only days after {freeze['data_end_at_freeze']} "
             "count here, so this is the one result the design work cannot have influenced."]
    m = data.load_metrics(st.db, st.run_id, cycle=FORWARD_CYCLE)
    if m.empty:
        lines.append("")
        lines.append(f"No trading days since the freeze yet (data through {st.run['data_end']}). Each "
                     "`python scripts/run_pipeline.py --reuse-models` adds new days; `python "
                     "scripts/forward_test.py` prints the result.")
        return "\n".join(lines)
    lines += ["", "| Asset | Strategy | Days | Total return | Sharpe (above cash) | Max DD | Avg. exposure |",
              "|---|---|---|---|---|---|---|"]
    for a in st.assets:
        for s in st.strategies:
            if (a, s) not in m.index:
                continue
            r = m.loc[(a, s)]
            lines.append(f"| {ASSET_NAMES[a]} | {STRATEGY_NAMES[s]} | {int(r['Days'])} | "
                         f"{pct(r['Total Return'], 2, True)} | {num(r['Sharpe'])} | {pct(r['Max DD'], 1)} | "
                         f"{pct(r['Avg. Exposure'], 0)} |")
    lines += ["", "*A few weeks of data say almost nothing; judge the forward test after months.*"]
    return "\n".join(lines)


BLOCKS = {
    "status": block_status, "headline": block_headline, "results": block_results,
    "significance": block_significance, "variants": block_variants, "episodes": block_episodes,
    "profile": block_profile, "caveats": block_caveats, "forward": block_forward,
}


def render(text, st):
    for name, fn in BLOCKS.items():
        pattern = re.compile(rf"(<!-- generated:{name} -->\n).*?(<!-- /generated:{name} -->)", re.S)
        if not pattern.search(text):
            raise SystemExit(f"README is missing the generated:{name} markers.")
        body = fn(st).rstrip("\n") + "\n"
        text = pattern.sub(lambda m: m.group(1) + body + m.group(2), text)
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if README.md is out of date")
    args = parser.parse_args()
    with open(README, encoding="utf-8") as f:
        old = f.read()
    new = render(old, Store())
    if args.check:
        if new != old:
            sys.exit("README.md results are out of date: run python scripts/update_readme.py")
        print("README.md results are up to date.")
        return
    with open(README, "w", encoding="utf-8") as f:
        f.write(new)
    print("README.md results regenerated." if new != old else "README.md already up to date.")


if __name__ == "__main__":
    main()
